const assert=require('assert');
const {create,run,json}=require('./verify-draft.cjs');
(async()=>{
 const t=create();const r=s=>run(t.context,s);await r('bootCatalog()');
 r("S.team=0;S.pick=['marcus','eli','jaylen','noah','darius','malik','andre','ty'];autoStarters();saveAll()");
 const schedule=json(t.context,'availabilityWeek()');
 assert(Object.values(schedule).some(a=>a.out),'Fixture contains unavailable players');
 r('startWeekend();tipOff();suggestLineup()');
 assert(r('validFive(lineupDraft)'));
 assert(r('lineupDraft.every(availablePlayer)'));
 const absent=Object.keys(schedule).filter(id=>schedule[id].out);
 r('confirmPregame();finishGame("calm")');
 const box=json(t.context,'S.statLog[0].boxScore');
 assert(absent.every(id=>!box.players.some(p=>p.playerId===id)),'Absent players have no stats');
 assert.equal(box.players.reduce((n,p)=>n+p.pts,0),box.totals.pts);
 assert(r('D.circuit.feed.some(x=>x.tag==="FINAL BUZZER")'));
 assert(r('D.circuit.feed.every(x=>!/(illness|vacation|soccer)/i.test(x.text))'),'Private attendance stays off feed');
 r('advanceGame();S.screen="support"');
 await r('inventoryChange(c=>{c.support={shooting:1,scout:1,defense:1}})');
 const before=r('player("marcus").s');
 await r('useCircuitTrainer("marcus")');
 assert.equal(r('inventoryRead().support.shooting'),0);
 assert.equal(r('player("marcus").s'),Math.min(99,before+2));
 await r('useCircuitTrainer("marcus")');
 assert.equal(r('player("marcus").s'),Math.min(99,before+2),'Cannot spend trainer twice');
 await r('equipCircuitCoach("scout")');assert.equal(r('inventoryRead().activeCoach'),'scout');
 r('hqProfile=()=>{};D.points=40');const observed=r('scoutState("eli").seen');
 r('scoutVisit("eli")');assert.equal(r('scoutState("eli").seen'),observed+2);
 assert.equal(r('D.points'),32);
 assert(r('scoutPanel("eli").includes("UNOBSERVED")'));
 await r('syncAccountSave()');const next=create(new Map(t.storage),t.remote);await run(next.context,'bootCatalog()');
 assert.equal(run(next.context,'inventoryRead().activeCoach'),'scout');
 assert.equal(run(next.context,'inventoryRead().support.shooting'),0);
 assert.equal(run(next.context,'scoutState("eli").seen'),observed+2);
 assert.deepEqual(json(next.context,'availabilityWeek()'),json(t.context,'availabilityWeek()'));
 r('S.screen="packs";PR.phase="idle"');await r('prCommitFiveCards()');
 assert.equal(r('inventoryRead().last.cards.length'),5);
 assert(r('!!inventoryRead().last.bonusSupport'));
 console.log('PASS: eligible five; absent-player stats excluded; conserved scoring; private attendance; event feed; trainer consumption/effect; coach equip; accelerated scouting; account restore; five-player plus support pack.');
})().catch(e=>{console.error(e);process.exit(1)});
